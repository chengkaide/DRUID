"""
druid.reduction.ablation —— 剥蚀区间自动定位 & 气体空白
=====================================================

一次激光剥蚀的时间序列长这样（以 238U 信号为例）：

    高能 ▏                    ╱‾‾‾‾‾‾‾‾‾‾╲___
         ▏                   ╱              ╲
         ▏__________________╱                ╲________…
         └──────┬──────────┴──────────┬───────┴──────
            气体空白              剥蚀(~30 s)     冲洗(washout)
           (laser off)          (laser on)      (laser off)
            ~0~300 cps          ~1e5~1e6 cps   拖尾数百 cps

要做的三件事：
    1. 找出可信的剥蚀起止时刻 ta0 / ta1
    2. 取 ta0 之前的一段作为**气体空白**（载气 + 仪器本底 + 残留 Hg）
    3. 再把区间两端各裁掉 trim 秒，避开开/关激光时的**瞬态尖峰**

为什么不能直接整段积分
----------------------
· 空白段没有信号，只会稀释比值（把分子分母同时抬高一个常数）：
  238U 抬得多一列，206Pb 抬得更明显，**比值必然失真**；
· washout 尾巴是残留在样品池里的气溶胶，同位素组成已经被分馏，
  且随抵达质量的时间延迟而偏移，同样不能算进有效信号。
"""
from __future__ import annotations

import numpy as np


# ─────────────────────────────────────────────────────────────────────────────
# 工具：最长连续 True 段
# ─────────────────────────────────────────────────────────────────────────────
def _longest_run(mask: np.ndarray):
    """
    找出布尔数组中最长的一段连续 True，返回 (起始下标, 结束下标+1)。

    为什么需要它
    ------------
    信号可能在阈值附近来回抖动，出现若干段短暂的 True 区间。
    我们只想要"真正那一段"剥蚀，所以用**最长连续段**来滤掉零星毛刺。
    """
    best = (0, 0)            # (start, stop)，stop 是开区间
    i, n = 0, mask.size
    while i < n:
        if mask[i]:
            j = i
            while j < n and mask[j]:     # 一直往后扫到 False 为止
                j += 1
            if j - i > best[1] - best[0]:  # 比目前最长还长 → 更新
                best = (i, j)
            i = j                          # 跳过这一整段
        else:
            i += 1
    return best


# ─────────────────────────────────────────────────────────────────────────────
# 一、定位剥蚀区间
# ─────────────────────────────────────────────────────────────────────────────
def find_ablation(t, u, k=8.0, frac=0.03):
    """
    用 **两级阈值** 定位剥蚀起止时刻。

    参数
    ----
    t    : 时间轴数组 (s)
    u    : 238U 的 cps 数组（用 U 是因为它信号最强、形态最清楚）
    k    : 第一级阈值的 σ 倍数。主要作用是**兜底**——
           万一某个点信号极弱，第二级阈值会退化，靠它兜住。
    frac : 第二级阈值 = 峰值的百分之多少（默认 3%）

    两级阈值为什么都要
    ------------------
    · thr1（本底 + k·σ）：理论上够用，但实测 iCAP RQ 的 washout 拖尾
      在关激光后 10 s 仍有 100~200 cps，远高于本底噪声，
      只用 thr1 会把窗口一直拉到记录末尾（把大量零信号混进来）。
    · thr2（bg + frac·峰高）：直接按"相对于峰值的比例"截断，
      能干净地砍掉拖尾。**以 thr2 为主**。
    · 两者取 max，保证任何情况下阈值都不会落进本底噪声里。

    返回
    ----
    (t_start, t_end)，单位是秒。
    若两级都失败（数据异常），退化为整个时间轴。
    """
    n = u.size
    # ── 本底估计 ──
    # 取前 30% 作为"激光还没开"的参考段（至少 5 个点，避免样本太小）
    nb = max(int(0.30 * n), 5)
    base = u[:nb]
    bg = float(np.median(base))                                   # 中位数比均值抗毛刺
    sd = 1.4826 * float(np.median(np.abs(base - bg))) + 1e-9      # MAD → σ，加 1e-9 防全零
    thr1 = bg + k * max(sd, np.sqrt(max(bg, 1.0)))                # 泊松噪声兜底 sqrt(bg)

    # ── 峰值比例阈值 ──
    # 用 98 分位而不是最大值：最大值可能是个随机尖刺
    peak = float(np.percentile(u, 98))
    thr2 = max(thr1, bg + frac * (peak - bg))

    # ── 先用严格阈值 thr2 找最长连续段 ──
    i0, i1 = _longest_run(u > thr2)
    if i1 - i0 < 3:                       # 太短说明失败，退回宽松阈值 thr1
        i0, i1 = _longest_run(u > thr1)
    if i1 - i0 < 3:                       # 还是不行 → 数据本身有问题，放弃切割
        i0, i1 = 0, n
    # np.clip 保证下标不越界（i1 可能等于 n，这里取最后一个有效下标）
    return float(t[i0]), float(t[min(i1, n - 1)])


# ─────────────────────────────────────────────────────────────────────────────
# 二、气体空白
# ─────────────────────────────────────────────────────────────────────────────
def blank_mean(t, arr, t_ab0, dur=15.0):
    """
    取**剥蚀开始前**的一段信号作为气体空白，返回其均值 (cps)。

    为什么取"紧挨着剥蚀之前"的那一段，而不是文件最开头
    ---------------------------------------------------
    气体空白的主要成分是载气里的 Hg（来自氩气瓶杂质与管路），
    它会随时间缓慢漂移。取**时间上最接近**剥蚀的一段，
    才能代表剥蚀那几分钟内的真实本底水平。

    为什么留 0.5 s 的安全间隔
    --------------------------
    激光的实际起跳时刻与电信号有一点延迟，
    紧挨着 ta0 的最后 0.5 s 可能已经被"污染"了，必须让开。

    参数
    ----
    t     : 时间轴 (s)
    arr   : 任意通道的 cps 数组
    t_ab0 : 剥蚀起始时刻
    dur   : 往前取多少秒（默认 15 s）

    返回
    ----
    空白均值 (float)。若可用点数太少则返回 0.0（宁可不扣，也不用离谱的值）。
    """
    # 窗口：[t_ab0 - dur - 0.5, t_ab0 - 0.5]
    m = (t >= max(0.0, t_ab0 - dur - 0.5)) & (t <= t_ab0 - 0.5)
    if m.sum() < 5:
        # 剥蚀起点太靠前，退而求其次：从 0 到 ta0-0.5 全取
        m = (t >= 0) & (t <= t_ab0 - 0.5)
    return float(arr[m].mean()) if m.sum() >= 2 else 0.0


def subtract_blank(t, raw: dict, t_ab0, dur=15.0):
    """
    对**所有通道**统一扣除气体空白。

    返回
    ----
    (net_dict, blank_dict)
        net_dict   : {质量数: 扣完空白后的净信号}
        blank_dict : {质量数: 各自扣掉的空白值}（留档，便于检查 Hg 本底高低）

    注意
    ----
    净信号允许为负 —— 这是正常的统计学现象（信号等于本底时，扣除后随机波动）。
    不要在这里 clip 到 0，那会引入系统性正偏差。真正需要处理"负值"
    的地方是后面的比值环节（那里有专门的保护）。
    """
    net, blank = {}, {}
    for m, v in raw.items():
        b = blank_mean(t, v, t_ab0, dur)
        blank[m] = b
        net[m] = v - b
    return net, blank
