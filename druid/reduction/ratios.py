"""
druid.reduction.ratios —— 由净信号算同位素比值和不确定度
=======================================================

这是整个软件包的**心脏**。它做四件事：

    ① 204Hg 干扰校正     202Hg / 4.35 → 204Hg，从 204 通道里减掉
    ② 普通铅显著性检验   204Pb 真的存在吗？不存在就别硬扣（**极其关键**）
    ③ 普通铅校正         Stacey-Kramers 模型，迭代收敛求组成
    ④ jackknife 刀切法   同时给出 σ 和 相关系数 ρ（画协和椭圆必需）

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
⚠ 本文件里最重要的一段：为什么 204 校正要做显著性检验
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
真实数据的残酷现实：
    · 204Pb 信号通常只有 **几 ~ 几十 cps**
    · 而 204Hg 本底可达 **数百 cps**
    · 我们要的是：(204 通道 − 204Hg/4.35) 这个**差值**

这是典型的"两个大数相减求小数"，残余的不确定性 blown up 到和信号本身同量级。
实测本批次 91500 主标：i204 在 **−6 ~ +17 cps** 之间纯随机波动。

如果不管显著不显著一律扣普通铅：
    → 把噪声随机的一部分当成普通铅扣掉
    → 206Pb 被扣掉一点点（影响小，因为 206Pb 大）
    → **207Pb 被扣掉相对量大得多的份额**（207Pb 本来就少）
    → 207Pb/206Pb 系统性偏低 → 207Pb/206Pb 年龄大幅偏年轻

所以这一步不是"锦上添花的讲究"，而是数据能不能用的分水岭。
"""
from __future__ import annotations

from typing import Dict, Optional, Tuple

import numpy as np

from ..core.common_lead import stacey_kramers
from ..core.constants import HG202_204, MASSES_NEEDED
from ..core.geochronology import age76


# ─────────────────────────────────────────────────────────────────────────────
# 一、单组信号 → 五个比值
# ─────────────────────────────────────────────────────────────────────────────
def _chain(i238, i206, i207, i208, i232, i204, sk, use_common):
    """
    给定一组积分强度，算出五个比值。

    参数
    ----
    i238/i206/i207/i208/i232 : 各质量数的强度（标量或数组均可）
    i204                     : **估算的** 204Pb 强度（已做过 Hg 校正）
    sk                       : 普通铅三个比值 (206/204, 207/204, 208/204)
    use_common               : 是否执行普通铅扣除。False 时 i204 被忽略。

    返回
    ----
    (R68, R76, R82, ThU, f206)
        R68  : 206Pb/238U
        R76  : 207Pb/206Pb
        R82  : 208Pb/232Th
        ThU  : 232Th/238U  （严格说是"灵敏度未校正的表观 Th/U"，
                            真正的 Th/U 需要元素分馏校正，这里只作为岩性指标）
        f206 : 普通铅 206Pb 占总 206Pb 的比例（重要的质控指标）

    为什么这里允许除零
    ------------------
    在 jackknife 里会出现个别 replicate 分母为 0 的情况。
    直接让它产生 inf/nan，后面的 nan 安全聚合（np.nanmean 等）会处理，
    比在这里 raise 或者强行替换成 0 都要好。
    """
    if use_common:
        # 普通铅的 206/207/208 = 204Pb × 各自与普通铅 204 的比值
        c6 = i204 * sk[0]
        c7 = i204 * sk[1]
        c8 = i204 * sk[2]
    else:
        # 不做校正时把份额置零，这样后面的减法等价于"不扣"
        z = np.zeros_like(np.asarray(i204, float))
        c6 = c7 = c8 = z

    r6 = i206 - c6          # 放射成因 206Pb
    r7 = i207 - c7          # 放射成因 207Pb

    with np.errstate(invalid="ignore", divide="ignore"):
        return (r6 / i238,                                    # 206Pb/238U
                r7 / r6,                                      # 207Pb/206Pb
                (i208 - c8) / i232,                           # 208Pb/232Th
                i232 / i238,                                  # Th/U
                c6 / np.where(i206 != 0, i206, np.nan))       # f206


# ─────────────────────────────────────────────────────────────────────────────
# 二、核心：窗口还原
# ─────────────────────────────────────────────────────────────────────────────
def reduce_interval(net: Dict[int, np.ndarray],
                    mask: np.ndarray,
                    n_sigma: float = 2.0,
                    fix: Optional[Tuple[float, Tuple[float, float, float]]] = None
                    ) -> Optional[dict]:
    """
    在一个时间窗口内积分并还原出全部比值与不确定度。

    参数
    ----
    net     : {质量数: 净信号数组}，由 trace.load_spot 得到
    mask    : 布尔数组，标明哪些时间点属于本窗口
    n_sigma : 204Pb 显著性门槛。要求 i204 > n_sigma × σ(i204) 才执行校正。
              默认 2σ（约 95% 置信度）。调到更小更容易触发校正（风险更高）。
    fix     : (f206, sk) 二元组。**深度剖面专用**：
              传入整段算好的普通铅比例，强制应用到每个短窗口。
              见下面 "fix 模式" 的说明。

    返回
    ----
    dict 或 None（窗口内有效点数 < 5 时返回 None）
        R68, R76, R82, ThU, f206  : 五个比值
        s68, s76, rho             : 206Pb/238U 与 207Pb/206Pb 的 1σ 与相关系数
        U_cps, n_cycles, i204, sk : 质控信息
    """
    # 通道检查：一个都不能少。
    # 通道全集用 core.constants.MASSES_NEEDED —— 本文件曾经自己写了一份同样的元组
    # (_NEED)，两处并存就是 AGENTS.md §6.1 警告的"同一事实两个出处"：
    # 哪天常量表里加了通道，这里不会跟着变，而漏检一个通道的后果是静默算错年龄。
    if not all(k in net for k in MASSES_NEEDED):
        raise KeyError(f"缺少通道: {sorted(set(MASSES_NEEDED) - set(net))}")

    # 取出窗口内的子信号
    a = {k: net[k][mask] for k in MASSES_NEEDED}
    n = a[238].size
    if n < 5:
        # 点数太少，jackknife 的方差估计完全不可靠，直接放弃这个窗口
        return None

    # ── 窗口平均强度 ──
    mean = {k: float(v.mean()) for k, v in a.items()}

    # ══════════════════════════════════════════════════════════════════════
    # 步骤 1：204Hg 干扰校正，得到"原始"的 204Pb 估计
    # ══════════════════════════════════════════════════════════════════════
    # 204 通道上测到的总量 = 204Pb（想要）+ 204Hg（干扰）
    # 而 204Hg = 202Hg / 4.35，202Hg 无干扰可直接读
    i204_raw = mean[204] - mean[202] / HG202_204

    # ══════════════════════════════════════════════════════════════════════
    # 步骤 2：**显著性检验** —— 这个 204Pb 是真的吗？
    # ══════════════════════════════════════════════════════════════════════
    # 做法：用刀切法估计 i204 本身的标准误 σ(i204)，
    #       只有当 i204 显著大于 n_sigma·σ 时才认为"确有普通铅"。
    #
    # 刀切（delete-1 jackknife）：依次去掉第 j 个 cycle，
    #   用剩下 n-1 个算均值 → 得到 n 个"伪值"，它们的离散程度即方差估计：
    #       Var = (n-1)/n · Σ (x_(j) − x̄)²
    #   系数 (n-1)/n 是刀切法方差的标准修正因子。
    jk204 = ((a[204].sum() - a[204]) / (n - 1)          # 去掉第 j 点后的 204 通道均值
             - (a[202].sum() - a[202]) / (n - 1) / HG202_204)   # 同理 202 → 推算的 Hg 部分
    s_i204 = float(np.sqrt((n - 1) / n * np.sum((jk204 - jk204.mean()) ** 2)))
    # 显著性判据：信号 > n_sigma × 噪声
    sig204 = bool(i204_raw > n_sigma * s_i204) if s_i204 > 0 else False

    # ══════════════════════════════════════════════════════════════════════
    # 步骤 3：确定普通铅组成 sk 与 204Pb 强度 i204
    # ══════════════════════════════════════════════════════════════════════
    t_guess = 500.0   # 迭代初值随便给个中间年龄即可，3~4 轮就收敛

    if fix is not None:
        # ──────────────────────────────────────────────────────────────
        # fix 模式：用于深度剖面的短窗口
        # ──────────────────────────────────────────────────────────────
        # 窗口只有几秒，204Pb 的绝对计数可能只有个位数，
        # 在这个尺度上独立做 204 校正就是纯噪声。
        #
        # 但普通铅在**同一个剥蚀点内**是近似恒定的（它来自同一批包裹体），
        # 于是合理做法是把整段算出来的 f206 "借用"到每个窗口：
        #       c206 = f206 × i206(窗口)
        #       c204 = c206 / (206Pb/204Pb)_common
        # 这样窗口之间的相对变化才不被 204 噪声淹没。
        f206_fix, sk_fix = fix
        use = bool(f206_fix > 0)
        if use:
            i204 = f206_fix * mean[206] / sk_fix[0]
            sk = sk_fix
        else:
            # 整段没有检测到普通铅 → 短窗口也不扣
            i204, sk = 0.0, (0.0, 0.0, 0.0)
    else:
        # ──────────────────────────────────────────────────────────────
        # 独立模式：常规整段还原
        # ──────────────────────────────────────────────────────────────
        use = sig204
        i204 = i204_raw if use else 0.0
        if use:
            # Stacey-Kramers 需要知道锆石年龄才能给出铅组成，
            # 而年龄又依赖铅组成 —— 鸡生蛋问题。
            # 解法：不动点迭代。从 500 Ma 出发，反复：
            #     假设年龄 t → 查普通铅组成 sk → 扣除后算 207Pb/206Pb
            #     → 反解新年龄 t' → 若 |t'−t| < 0.5 Ma 认为收敛
            # 这个迭代是压缩映射，3~4 次必收敛，所以上限写死 4 次即可。
            for _ in range(4):
                sk = stacey_kramers(t_guess)
                _, r76, _, _, _ = _chain(mean[238], mean[206], mean[207],
                                         mean[208], mean[232], i204, sk, True)
                if not np.isfinite(r76) or r76 <= 0:
                    # 迭代炸了（比如数据异常）→ 放弃普通铅校正，走不扣的路线
                    use = False
                    break
                tn = float(age76(r76))
                if abs(tn - t_guess) < 0.5:
                    break
                t_guess = tn
        sk = stacey_kramers(t_guess) if use else (0.0, 0.0, 0.0)

    # ══════════════════════════════════════════════════════════════════════
    # 步骤 4：算中心值
    # ══════════════════════════════════════════════════════════════════════
    R68, R76, R82, ThU, f206 = _chain(mean[238], mean[206], mean[207],
                                      mean[208], mean[232], i204, sk, use)

    # ══════════════════════════════════════════════════════════════════════
    # 步骤 5：jackknife 估计 σ 与相关系数 ρ
    # ══════════════════════════════════════════════════════════════════════
    # 为什么不用泊松统计 σ = √N：
    #   泊松只描述"计数过程本身的随机性"，抓不到等离子体闪烁噪声
    #   (flicker noise / 1/f 噪声)，而后者在 ICP-MS 上往往是主导项。
    #   刀切法从数据本身估计离散度，两种噪声都会被算进去。
    #
    # 为什么必须给出 ρ：
    #   206Pb/238U 与 207Pb/206Pb 共用同一个 206Pb 测量值，两者强相关
    #   （典型 ρ ≈ 0.7~0.9）。画协和曲线时必须用这个 ρ 才算得出正确的
    #   椭圆倾角；忽略相关性会把误差椭圆画成"正着"的，视觉上失真。
    jk = {k: (v.sum() - v) / (n - 1) for k, v in a.items()}

    if fix is not None and use:
        # fix 模式下，每个 replicate 的 204Pb 也按 window 的 206 强度比例推导
        j204v = f206_fix * jk[206] / sk_fix[0]
    else:
        j204 = jk[204] - jk[202] / HG202_204
        # np.where(j204 > 0, ...)：负值说明该 replicate 里"没有普通铅"，
        # 把它钳到 0（而不是保留负值去随机放大/缩小 206Pb）
        j204v = np.where(j204 > 0, j204, 0.0) if use else np.zeros(n)

    j68, j76, _, _, _ = _chain(jk[238], jk[206], jk[207], jk[208], jk[232],
                               j204v, sk, use)

    fac = (n - 1) / n      # 刀切方差的标准修正因子
    # nan-aware：个别 replicate 可能因为除零产生 nan，用 nanmean 跳过它们
    s68 = float(np.sqrt(fac * np.nansum((j68 - np.nanmean(j68)) ** 2)))
    s76 = float(np.sqrt(fac * np.nansum((j76 - np.nanmean(j76)) ** 2)))

    with np.errstate(invalid="ignore", divide="ignore"):
        # 协方差同样用刀切伪值估计
        cov = fac * np.nansum((j68 - np.nanmean(j68)) * (j76 - np.nanmean(j76)))
        # ρ = cov / (σ68·σ76)，并 clip 到 [-1, 1]（数值误差可能让它略微越界）
        rho = float(cov / (s68 * s76)) if (s68 > 0 and s76 > 0) else 0.0

    return dict(
        R68=float(R68), R76=float(R76), R82=float(R82),
        ThU=float(ThU), f206=float(f206),
        s68=s68, s76=s76, rho=float(np.clip(rho, -1.0, 1.0)),
        U_cps=float(mean[238]), n_cycles=int(n),
        i204=float(i204), sk=tuple(float(x) for x in sk),
        i204_significant=bool(sig204) if fix is None else None,
    )
