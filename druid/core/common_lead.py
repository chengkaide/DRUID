"""
druid.core.common_lead —— 普通铅（初始铅 / common Pb）同位素组成模型
==================================================================

什么是普通铅
------------
锆石结晶时，晶格**几乎**不接纳 Pb（Pb²⁺ 半径大、电价不匹配，分配系数极低），
所以理论上所有的 Pb 都应该是铀钍衰变产生的"放射成因铅"。
但现实中总会有少量**普通铅**（初始铅）混进来：
    · 矿物/流体包裹体（磷灰石、长石微包裹体）—— **最主要来源**
    · 裂隙中的次生铅
    · 样品表面污染、树脂/抛光膏残留
所以 U-Pb 定年的第一步永远是：**把普通铅从总 Pb 里剔除**。

怎么剔除
--------
普通铅里有一个关键的"化学惰性"同位素：**204Pb** —— 它不由任何放射性衰变产生，
其宇宙丰度在太阳系形成后就固定了。因此：

    **只要测到显著的 204Pb，就说明有普通铅**，而且可以按某个
    "普通铅同位素组成模型"把 206Pb、207Pb、208Pb 中的普通铅份额一并算出来扣掉。

Stacey & Kramers (1975) 两阶段模型
-----------------------------------
地球上铅的演化分两个阶段（经典近似）：
    阶段一：地球形成 (T0 = 4570 Ma) 到 T1 = 3700 Ma，μ1 = 238U/204Pb = 7.19
    阶段二：3700 Ma 至今，由于 U 被氧化搬运到地壳，μ2 = 9.74
    另有 κ = 232Th/238U = 4.0
给定锆石结晶年龄 t，模型的铅同位素组成就是"到 t 时刻为止累积的结果"，
因此：

    (206Pb/204Pb)_common = 初始值 + μ1·阶段一增量 + μ2·阶段二增量

为什么不用更精确的 modern Pb 模型（如 Cumming-Richards）
------------------------------------------------------
对本批次这种**低普通铅**锆石，204Pb 基本都在噪声水平，
普通铅校正对结果的影响本来就很小，模型的代际差异完全可以忽略。
反而保持与主流软件（Iolite/Isoplot）一致更重要。
"""
from __future__ import annotations

import numpy as np

from .constants import L232, L235, L238, U238_U235


def stacey_kramers(t_ma):
    """
    Stacey & Kramers (1975) 两阶段普通铅演化模型。

    参数
    ----
    t_ma : float 或 ndarray
        锆石结晶年龄，单位 Ma。**支持数组输入**（便于对一列窗口向量化）。

    返回
    ----
    (206Pb/204Pb, 207Pb/204Pb, 208Pb/204Pb) 三个同形状数组，
    即该年龄下普通铅应有的同位素组成。

    注意
    ----
    返回值是 **比值**，且是"样品在年龄 t 时圈闭的普通铅"之比，
    不要和"今日普通铅"混淆。
    """
    # ── 模型常数（地球铅演化的两阶段划分）──
    T0 = 4570e6   # 地球形成年龄，单位年
    T1 = 3700e6   # 两阶段分界，单位年（对应地球大氧化/地壳分异）
    mu1 = 7.19    # 阶段一的 238U/204Pb
    mu2 = 9.74    # 阶段二的 238U/204Pb（U 在地壳中富集）
    kap = 4.0     # κ = 232Th/238U

    # 把输入年龄从 Ma 换成"年"，并钳到 [0, 4570 Ma]：
    # 钳位是为了防止异常年龄进入 system 导致 exp() 溢出或给出荒谬比值
    t = np.clip(np.asarray(t_ma, float), 0.0, 4570.0) * 1e6

    # ── 206Pb/204Pb ──
    # 9.307 = 原始铅（Canyon Diablo 铁陨石，代表地球初始铅）的 206Pb/204Pb
    # 后两项分别是两个阶段里由 U 衰变累积的放射成因 206Pb（以 204Pb 归一化）
    p6 = (9.307
          + mu1 * (np.exp(L238 * T0) - np.exp(L238 * T1))     # 阶段一：T1→T0 期间累积
          + mu2 * (np.exp(L238 * T1) - np.exp(L238 * t)))     # 阶段二：t→T1 期间累积

    # ── 207Pb/204Pb ──
    # 同 206 的推导，但 λ 换成 λ235；且 235U 的原子数 = 238U / (238U/235U)，
    # 所以 μ 项要除以 U238_U235
    p7 = (10.294
          + (mu1 / U238_U235) * (np.exp(L235 * T0) - np.exp(L235 * T1))
          + (mu2 / U238_U235) * (np.exp(L235 * T1) - np.exp(L235 * t)))

    # ── 208Pb/204Pb ──
    # 232Th → 208Pb，Th 的量 = μ·κ（κ = Th/U），故多乘一个 kap
    p8 = (29.476
          + mu1 * kap * (np.exp(L232 * T0) - np.exp(L232 * T1))
          + mu2 * kap * (np.exp(L232 * T1) - np.exp(L232 * t)))

    return p6, p7, p8
