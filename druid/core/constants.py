"""
druid.core.constants —— 全局常量与标准物质库（"单一数据源"）
==========================================================

原则：**任何物理/化学数值常量在本项目中只允许出现一次**。
如果同一个衰变常数在两处各写一遍，迟早会改了一处忘了另一处，
而这种错误在同位素年代学里是致命的——不报错，只是悄悄给出错误的年龄。

所以本模块是唯一的数值出处，其余模块一律从这里 import。
"""
from __future__ import annotations

# ─────────────────────────────────────────────────────────────────────────────
# 一、放射性衰变常数（单位：a⁻¹，即"每年"）
# ─────────────────────────────────────────────────────────────────────────────
# 238U → 206Pb 的衰变常数，Steiger & Jäger (1977) 推荐值，国际通用
L238 = 1.55125e-10

# 235U → 207Pb 的衰变常数，Steiger & Jäger (1977)
L235 = 9.8485e-10

# 232Th → 208Pb 的衰变常数（本项目算 Th/U 用得上）
L232 = 4.9475e-11

# ─────────────────────────────────────────────────────────────────────────────
# 二、天然铀同位素比 238U/235U
# ─────────────────────────────────────────────────────────────────────────────
# 经典值是 137.88（Steiger & Jäger），但 Hiess et al. (2012) 精测给出 137.818。
# 这个值直接决定 207Pb/235U = (207Pb/206Pb)×(206Pb/238U)×(238U/235U) 的换算，
# 也决定 207Pb/206Pb 年龄方程的系数，务必与所使用的标准物质参考值配套。
U238_U235 = 137.818

# ─────────────────────────────────────────────────────────────────────────────
# 三、质谱干扰常数
# ─────────────────────────────────────────────────────────────────────────────
# 氩气/载气中的 Hg 会在 204 质量数上产生 204Hg，与 204Pb 完全重叠，无法分辨。
# 好消息是天然 Hg 同位素组成基本恒定，可用无干扰的 202Hg 反推：
#     204Hg = 202Hg / 4.35
# 4.35 是 202Hg/204Hg 的天然丰度比。这是本还原流程里第一件必须做的事，
# 不做的话 204Pb 会被系统性抬高，进而"扣"出虚假的普通铅。
HG202_204 = 4.35

# ─────────────────────────────────────────────────────────────────────────────
# 四、还原流程需要的通道（质量数）
# ─────────────────────────────────────────────────────────────────────────────
# MASSES_NEEDED：一个测点要能还原出年龄，**必须**同时具备这些通道。
#   202 → 推算 204Hg（干扰监测）
#   204 → 普通铅指示（若显著）
#   206 → 放射成因 206Pb（238U 的子体）
#   207 → 放射成因 207Pb（235U 的子体）
#   208 → 放射成因 208Pb（232Th 的子体，用于 208Pb/232Th 年龄）
#   232 → 232Th（算 Th/U、Th-Pb 年龄）
#   238 → 238U（分母，同时用作"激光是否开火"的判据）
MASSES_NEEDED = (202, 204, 206, 207, 208, 232, 238)

# SUM_MASSES：深度剖面里按窗口做"计数加权合成"时用到的通道集合。
# 因为在极短的窗口里直接算比值噪声太大，改为对窗口内的 **积分计数求和**，
# 再统一做比值。这里的顺序不影响结果，仅用于循环遍历。
SUM_MASSES = (206, 207, 208, 232, 238)

# ─────────────────────────────────────────────────────────────────────────────
# 五、标准物质（锆石 U-Pb 定年标样）参考值库
