"""
druid.core.geochronology —— U-Pb 年龄 ⇄ 同位素比值的相互转换
==========================================================

三套年龄体系
------------
    206Pb/238U  → 年轻锆石最准（238U 衰变快，累积的放射成因 Pb 多）
    207Pb/235U  → 精度差（235U 丰度只有 0.72%，207Pb 信号弱）
    207Pb/206Pb → 只在 **老锆石**（>1 Ga）上才谈得上精度，
                  但它的好处是**不依赖 U 含量**，也不受 Pb/U 元素分馏影响

基本方程（以 206Pb/238U 为例）
----------------------------
    (206Pb/238U)_放射成因 = exp(λ238 · t) − 1
反解年龄：
    t = ln(1 + 206Pb/238U) / λ238

所有函数都支持标量 / numpy 数组输入，便于对整列数据向量化运算。
"""
from __future__ import annotations

import numpy as np

from .constants import L235, L238, U238_U235


# ─────────────────────────────────────────────────────────────────────────────
# 一、"年龄 → 比值"正演
# ─────────────────────────────────────────────────────────────────────────────
def r68_of_age(t_ma):
    """
    年龄 (Ma) → 206Pb/238U 比值。

    参数
    ----
    t_ma : float 或 ndarray，年龄，单位百万年 (Ma)

    返回
    ----
    206Pb/238U 比值（无量纲）

    实现要点
    --------
    用 numpy.expm1(x) = exp(x) - 1 而不是 np.exp(x) - 1：
    当 t 很小时 exp(λt)-1 ≈ λt 是两个相近数相减，expm1 由标准库
    专门实现了数值稳定的计算路径，避免有效数字损失。
    """
    # 先把 Ma 换算成年：1 Ma = 1e6 a
    # age * 1e6 → 年
    return np.expm1(L238 * np.asarray(t_ma, float) * 1e6)


def r76_of_age(t_ma, u238_u235=U238_U235):
    """
    年龄 (Ma) → 207Pb/206Pb 比值。

    推导
    ----
        207Pb* = 235U · (exp(λ235·t) − 1)
        206Pb* = 238U · (exp(λ238·t) − 1)

    两式相除：
        207Pb*/206Pb* = (235U/238U) · [exp(λ235·t) − 1] / [exp(λ238·t) − 1]

    注意分母上是 235U/238U = 1/(238U/235U)，**不要搞反**。
    """
    # Ma → a
    t = np.asarray(t_ma, float) * 1e6
    # 分子：235U 子系统累积的放射成因 207Pb（相对 235U 原子数）
    num = np.expm1(L235 * t)
    # 分母：238U 子系统累积的放射成因 206Pb（相对 238U 原子数）
    den = np.expm1(L238 * t)
    # 乘同位素丰度比 235U/238U = 1 / (238U/235U)
    return num / (den * u238_u235)


# ─────────────────────────────────────────────────────────────────────────────
# 二、"比值 → 年龄"反演
# ─────────────────────────────────────────────────────────────────────────────
def age68(r68):
    """
    206Pb/238U 比值 → 年龄 (Ma)。

        t = ln(1 + r) / λ238 / 1e6

    为什么用 log1p：r 很小时 ln(1+r)≈r，log1p 数值更稳定。
    为什么 clip 到 > −0.999999：net 信号可能为负（空白扣除后），
    此时 1+r ≤ 0 会让对数发散；钳到一个极小正值，让结果退化为一个
    接近 0 的负年龄，而不是 NaN —— NaN 会在后续加权平均里"传染"。
    """
    # 保证对数参数为正
    safe = np.maximum(np.asarray(r68, float), -0.999999)
    # ln(1+r) / λ → 年；再 /1e6 → Ma
    return np.log1p(safe) / L238 / 1e6


def age75(r75):
    """207Pb/235U 比值 → 年龄 (Ma)。同 age68，只是衰变常数换成 λ235。"""
    safe = np.maximum(np.asarray(r75, float), -0.999999)
    return np.log1p(safe) / L235 / 1e6


def age76(r76, u238_u235=U238_U235):
    """
    207Pb/206Pb 比值 → 年龄 (Ma)。

    为什么要用二分法
    ----------------
    207Pb/206Pb 的年龄方程是 **隐式的**：r = f(t) 无法解析反解出 t = f⁻¹(r)
    （两个不同 λ 的指数项之比）。工程上有两种选择：
      ① 数值求根（牛顿法 / 二分法）
      ② 泰勒级数近似公式
    这里选二分法，因为它**绝对收敛**：只要 f(t) 在 [1 Ma, 5000 Ma] 上单调
    （放射性累积当然是单调增），二分就一定收敛；牛顿法在某些区间会跳飞。

    80 次二分足够：区间长度每次减半，5000/2^80 远小于计算机精度，
    再多迭代没有任何收益，白白浪费时间。
    """
    r0 = np.asarray(r76, float)
    r = np.atleast_1d(r0)  # 统一成数组，方便后面的向量化二分
    # 二分初始区间下界 1 Ma、上界 5000 Ma（覆盖地球年龄，锆石不可能超范围）
    lo = np.full(r.shape, 1.0)
    hi = np.full(r.shape, 5000.0)

    with np.errstate(invalid="ignore", divide="ignore"):
        for _ in range(80):
            mid = 0.5 * (lo + hi)                      # 取区间中点
            val = np.expm1(L235 * mid * 1e6) / (
                np.expm1(L238 * mid * 1e6) * u238_u235)  # 正演得到该中点对应的比值
            inc = val < r                              # True 表示该点"比目标年轻"，真实年龄更大
            lo = np.where(inc, mid, lo)                # 真 → 抬高下界
            hi = np.where(inc, hi, mid)                # 假 → 压低上界

    out = 0.5 * (lo + hi)                              # 收敛后取最终区间中点
    # 标量输入就返回标量，保持调用方的使用习惯一致
    return float(out[0]) if r0.ndim == 0 else out


# ─────────────────────────────────────────────────────────────────────────────
# 三、三个比值之间的换算
# ─────────────────────────────────────────────────────────────────────────────
def r75_from(r68, r76, u238_u235=U238_U235):
    """
    由实测的 206Pb/238U 与 207Pb/206Pb 推算 207Pb/235U。

    为什么不独立测 235U：235U 丰度只有 0.72%，直接测信号太弱，
    信噪比远差于用 238U 换算。这是 U-Pb 年代学的标准做法。

        (207Pb/235U) = (207Pb/206Pb) × (206Pb/238U) × (238U/235U)

    中间两项相除时 206Pb 约掉：(207Pb/206Pb)·(206Pb/238U) = 207Pb/238U，
    再乘 238U/235U 把分母从 238U 换成 235U。
    """
    return np.asarray(r76, float) * np.asarray(r68, float) * u238_u235
